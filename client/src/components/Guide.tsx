/* ------------------------------ building blocks ------------------------------ */

function Section({
  n,
  title,
  children,
}: {
  n: string;
  title: string;
  children: React.ReactNode;
}) {
  return (
    <section className="mt-8">
      <h3 className="mb-2 flex items-baseline gap-2">
        <span className="bg-ink-900 px-1.5 py-0.5 text-xs font-bold text-white">
          {n}
        </span>
        <span className="text-base font-bold text-ink-900">{title}</span>
      </h3>
      <div className="text-sm leading-relaxed text-ink-700 [&_code]:bg-[#f4f2ea] [&_code]:px-1 [&_code]:text-ink-900">
        {children}
      </div>
    </section>
  );
}

function List({ children }: { children: React.ReactNode }) {
  return (
    <ul className="mt-2 flex flex-col gap-2 [&>li]:border-l-2 [&>li]:border-ink-200 [&>li]:pl-3">
      {children}
    </ul>
  );
}

function Callout({ children }: { children: React.ReactNode }) {
  return (
    <p className="mt-3 border-l-4 border-[#f7dd4b] bg-white px-3 py-2 text-sm text-ink-800">
      {children}
    </p>
  );
}

function Th({ children }: { children: React.ReactNode }) {
  return (
    <th className="px-2 py-1.5 text-xs font-bold uppercase tracking-wide text-ink-500">
      {children}
    </th>
  );
}

function Row({ a, b, c }: { a: string; b: string; c?: string }) {
  return (
    <tr className="border-b border-dotted border-ink-300 last:border-b-0">
      <td className="px-2 py-1.5 font-bold text-ink-900">{a}</td>
      <td className="px-2 py-1.5 text-ink-600">{b}</td>
      {c !== undefined && <td className="px-2 py-1.5 text-ink-600">{c}</td>}
    </tr>
  );
}

function State({
  color,
  ink,
  dashed,
  name,
  rule,
  what,
}: {
  color: string;
  ink?: string;
  dashed?: boolean;
  name: string;
  rule: string;
  what: string;
}) {
  return (
    <div className="flex flex-wrap items-baseline gap-x-3 gap-y-1 border-b border-dotted border-ink-300 px-3 py-2.5 last:border-b-0">
      <span
        className={`shrink-0 px-2 py-0.5 text-xs font-bold ${
          dashed
            ? "border border-dashed border-ink-400"
            : "border border-ink-900"
        }`}
        style={{ backgroundColor: color, color: ink || "#1a1a1a" }}
      >
        {name}
      </span>
      <span className="min-w-[12rem] flex-1 text-sm text-ink-800">{rule}</span>
      <span className="text-xs text-ink-400">{what}</span>
    </div>
  );
}

function Swatch({ c }: { c: string }) {
  return (
    <span
      className="inline-block h-2.5 w-2.5 translate-y-[1px] border border-ink-900"
      style={{ backgroundColor: c }}
    />
  );
}
